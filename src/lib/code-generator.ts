import { HEMIPROVE_DEPLOYMENTS, type HemiNetworkKey } from "@/lib/hemi-chain";
import { getDefaultProofSystemForBackend } from "@/lib/hemi-chain";
import type { SimulateReportJson } from "@/lib/simulate-engine";

export function generateSolidityRequesterCode(
  report: SimulateReportJson,
  network: HemiNetworkKey
): string {
  const dep = HEMIPROVE_DEPLOYMENTS[network];
  const ps = getDefaultProofSystemForBackend(report.backend);
  const isMainnetStaged = network === "mainnet" && !dep.router;
  const routerAddr =
    dep.router ?? "0xE1a492Dc6D57fCC2B6deb5B64087E69666cA470e";
  const tokenAddr =
    dep.hemiToken ?? "0x46955EdCF61b23a8c0b0d71428A9F1C07Bbf36cc";

  const weiScale = BigInt("1000000000000");
  const minWei = BigInt(Math.round(report.pricingRecommendation.minPriceHemi * 1e6)) * weiScale;
  const maxWei = BigInt(Math.round(report.pricingRecommendation.maxPriceHemi * 1e6)) * weiScale;

  const stagedNoticeSolidity = isMainnetStaged
    ? `\n *         NOTE (43111 STAGED): Hemi Mainnet HemiProve Router deployment is currently staged.\n *         \`0xE1a492Dc6D57fCC2B6deb5B64087E69666cA470e\` below is the active Hemi Sepolia (743111)\n *         rehearsal router; replace HEMI_PROVE once NEXT_PUBLIC_MAINNET_HEMIPROVE_ROUTER lands.${
        report.backend === "openvm"
          ? "\n *         WARNING: OPENVM_HALO2_V1 is registered on Sepolia (743111) only at launch."
          : ""
      }`
    : "";

  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/**
 * @title HemiProveJobRequester
 * @notice Auto-generated by HemiProve Hub from \`zkminer simulate\` sizing report.
 *         Targets ${dep.name} (Chain ID: ${dep.chainId}) using real \`hemiprove-abi\` v2 structs.
 *         ELF URI: ${report.elfUri}
 *         Proof System: ${ps.label} (${ps.id})${stagedNoticeSolidity}
 */

interface IERC20 {
    function approve(address spender, uint256 amount) external returns (bool);
}

interface IHemiProveCallback {
    function onProofFulfilled(
        bytes32 jobId,
        bytes32 programId,
        bytes calldata publicValues,
        bytes calldata callbackExtraData
    ) external;
}

interface IHemiProveRouter {
    struct JobDescriptor {
        bytes32 programId;
        bytes32 proofSystemId;
        address callbackContract;
        address assignedProver;
        bytes32 tag;
        bytes inputData;
        bytes callbackExtraData;
        bytes extraVerifierData;
        bytes32 expectedJournalHash;
        bytes32 journalFields;
    }

    struct JobConfig {
        uint96 minPrice;
        uint96 maxPrice;
        uint40 rampUpPeriod;
        uint8 curveType; // 0 = Linear, 1 = Quadratic
        uint40 fulfillmentTimeout;
        uint96 lockCollateralBps;
        uint96 speedPremium;
        uint40 exclusivityDuration;
        uint32 callbackGasLimit;
        bool excludeFromEwma;
        bool laxCallbackMode;
    }

    struct CycleVerifyConfig {
        uint64 expectedCycles;
        uint96 cycleCommitCollateral;
        uint8 snapshotMode;
        uint16 snapshotToleranceBps;
        uint16 snapshotFullBonusOvershootBps;
        uint16 snapshotUndershootPenaltyBps;
        uint16 snapshotFullPenaltyUndershootBps;
        uint16 snapshotResolverRewardBps;
    }

    struct BidConfig {
        uint40 underbidWindow;
        uint40 maxBiddingDuration;
        uint40 maxBidExtension;
        uint96 minBidDecrement;
        uint8 bidExtensionCurveType;
    }

    function submitJob(
        JobDescriptor calldata descriptor,
        JobConfig calldata config,
        CycleVerifyConfig calldata cycleConfig,
        BidConfig calldata bidConfig
    ) external returns (bytes32 jobId);
}

contract HemiProveJobRequester is IHemiProveCallback {
    // ${
      isMainnetStaged
        ? "STAGED (43111): 0xE1a492Dc6D57fCC2B6deb5B64087E69666cA470e is the active Sepolia (743111) rehearsal router"
        : `Active HemiProve v2 Router on ${dep.shortName}`
    }
    IHemiProveRouter public constant HEMI_PROVE = IHemiProveRouter(${routerAddr});
    IERC20 public constant HEMI_TOKEN = IERC20(${tokenAddr});

    bytes32 public constant PROGRAM_ID = ${report.programId};
    bytes32 public constant PROOF_SYSTEM_ID = ${ps.id}; // keccak256("${ps.label}")
    bytes32 public constant JOURNAL_PREDICATE_DOMAIN_V1 = keccak256("HemiProve.JournalPredicate.v1");

    mapping(bytes32 => bytes32) public verifiedJournalDigests;

    event ProofJobPosted(bytes32 indexed jobId, uint64 expectedCycles, uint96 minPrice, uint96 maxPrice);
    event ProofResultVerified(bytes32 indexed jobId, bytes32 journalDigest);

    function requestProof(bytes calldata guestStdin, bytes calldata expectedPublicValues)
        external
        returns (bytes32 jobId)
    {
        uint96 minOffer = ${minWei.toString()}; // ${report.pricingRecommendation.minPriceHemi} HEMI
        uint96 maxOffer = ${maxWei.toString()}; // ${report.pricingRecommendation.maxPriceHemi} HEMI

        // Approve maxOffer deposit in HEMI / tHEMI to HemiProve Router
        HEMI_TOKEN.approve(address(HEMI_PROVE), maxOffer);

        // Domain-separated FULL journal predicate commitment (or bytes32(0) for unconstrained journal)
        bytes32 expectedJournalHash = expectedPublicValues.length > 0
            ? keccak256(abi.encode(JOURNAL_PREDICATE_DOMAIN_V1, PROOF_SYSTEM_ID, PROGRAM_ID, expectedPublicValues))
            : bytes32(0);

        IHemiProveRouter.JobDescriptor memory desc = IHemiProveRouter.JobDescriptor({
            programId: PROGRAM_ID,
            proofSystemId: PROOF_SYSTEM_ID,
            callbackContract: address(this),
            assignedProver: address(0),
            tag: keccak256("hemiprove-hub-simulated"),
            inputData: guestStdin,
            callbackExtraData: "",
            extraVerifierData: "",
            expectedJournalHash: expectedJournalHash,
            journalFields: bytes32(0)
        });

        IHemiProveRouter.JobConfig memory cfg = IHemiProveRouter.JobConfig({
            minPrice: minOffer,
            maxPrice: maxOffer,
            rampUpPeriod: ${report.pricingRecommendation.rampUpPeriodSecs},
            curveType: 0, // Linear Reverse Dutch Auction
            fulfillmentTimeout: ${report.pricingRecommendation.fulfillmentTimeoutSecs},
            lockCollateralBps: 5000, // 50% prover collateral lock
            speedPremium: 0,
            exclusivityDuration: 0,
            callbackGasLimit: 250_000,
            excludeFromEwma: false,
            laxCallbackMode: false
        });

        IHemiProveRouter.CycleVerifyConfig memory cycleCfg = IHemiProveRouter.CycleVerifyConfig({
            expectedCycles: ${report.cycles},
            cycleCommitCollateral: 0,
            snapshotMode: 0,
            snapshotToleranceBps: 0,
            snapshotFullBonusOvershootBps: 0,
            snapshotUndershootPenaltyBps: 0,
            snapshotFullPenaltyUndershootBps: 0,
            snapshotResolverRewardBps: 0
        });

        IHemiProveRouter.BidConfig memory bidCfg = IHemiProveRouter.BidConfig({
            underbidWindow: 0,
            maxBiddingDuration: 0,
            maxBidExtension: 0,
            minBidDecrement: 0,
            bidExtensionCurveType: 0
        });

        jobId = HEMI_PROVE.submitJob(desc, cfg, cycleCfg, bidCfg);
        emit ProofJobPosted(jobId, ${report.cycles}, minOffer, maxOffer);
    }

    function onProofFulfilled(
        bytes32 jobId,
        bytes32,
        bytes calldata publicValues,
        bytes calldata
    ) external override {
        require(msg.sender == address(HEMI_PROVE), "Unauthorized caller");
        bytes32 digest = keccak256(publicValues);
        verifiedJournalDigests[jobId] = digest;
        emit ProofResultVerified(jobId, digest);
    }
}
`;
}

export function generateViemSubmitterScript(
  report: SimulateReportJson,
  network: HemiNetworkKey,
  rawStdin: string
): string {
  const dep = HEMIPROVE_DEPLOYMENTS[network];
  const ps = getDefaultProofSystemForBackend(report.backend);
  const isMainnetStaged = network === "mainnet" && !dep.router;
  const routerAddr =
    dep.router ?? "0xE1a492Dc6D57fCC2B6deb5B64087E69666cA470e";
  const tokenAddr =
    dep.hemiToken ?? "0x46955EdCF61b23a8c0b0d71428A9F1C07Bbf36cc";
  const chainExport = network === "mainnet" ? "hemiMainnet" : "hemiSepolia";

  const trimmedStdin = rawStdin.trim();
  const stdinExpr =
    trimmedStdin.startsWith("0x") && /^[0-9a-fA-F]+$/.test(trimmedStdin.slice(2))
      ? `"${trimmedStdin}" as Hex`
      : `toHex(${JSON.stringify(trimmedStdin)})`;

  const stagedCommentViem = isMainnetStaged
    ? `\n// NOTE (43111 STAGED): Mainnet HemiProve Router deployment is currently staged.\n// 0xE1a492Dc6D57fCC2B6deb5B64087E69666cA470e is the active Hemi Sepolia (743111) rehearsal router.\n// Update HEMI_PROVE_ROUTER once NEXT_PUBLIC_MAINNET_HEMIPROVE_ROUTER is published.${
        report.backend === "openvm"
          ? "\n// WARNING: OPENVM_HALO2_V1 is registered on Sepolia (743111) only at launch."
          : ""
      }`
    : "";

  return `import {
  createPublicClient,
  createWalletClient,
  http,
  parseUnits,
  keccak256,
  toBytes,
  toHex,
  zeroAddress,
  zeroHash,
  type Hex,
} from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { ${chainExport} } from "./hemi-chain";
import { HEMI_PROVE_ROUTER_ABI, ERC20_ABI } from "./hemiprove-abi";

/**
 * Auto-generated by HemiProve Hub (\`zkminer simulate\` Sizing Studio)
 * Network:      ${dep.name} (Chain ID ${dep.chainId})
 * ELF URI:      ${report.elfUri}
 * Proof System: ${ps.label} (${ps.id})
 * Sized Cycles: ${Number(report.cycles).toLocaleString()} (${report.vramTierRecommendation.tierLabel})
 */${stagedCommentViem}
const HEMI_PROVE_ROUTER = "${routerAddr}" as const;
const HEMI_TOKEN = "${tokenAddr}" as const;

async function main() {
  const account = privateKeyToAccount(process.env.PRIVATE_KEY as Hex);

  const publicClient = createPublicClient({
    chain: ${chainExport},
    transport: http("${dep.rpcUrl}"),
  });

  const walletClient = createWalletClient({
    account,
    chain: ${chainExport},
    transport: http("${dep.rpcUrl}"),
  });

  const minPrice = parseUnits("${report.pricingRecommendation.minPriceHemi}", 18);
  const maxPrice = parseUnits("${report.pricingRecommendation.maxPriceHemi}", 18);
  const inputData: Hex = ${stdinExpr};

  // 1. Approve HemiProve Router to escrow up to maxPrice HEMI
  const approveHash = await walletClient.writeContract({
    address: HEMI_TOKEN,
    abi: ERC20_ABI,
    functionName: "approve",
    args: [HEMI_PROVE_ROUTER, maxPrice],
  });
  await publicClient.waitForTransactionReceipt({ hash: approveHash });
  console.log("Approved HEMI escrow:", approveHash);

  // 2. Submit escalating Reverse Dutch Auction proving job
  const submitHash = await walletClient.writeContract({
    address: HEMI_PROVE_ROUTER,
    abi: HEMI_PROVE_ROUTER_ABI,
    functionName: "submitJob",
    args: [
      {
        programId: "${report.programId}",
        proofSystemId: "${ps.id}", // ${ps.label}
        callbackContract: zeroAddress,
        assignedProver: zeroAddress,
        tag: keccak256(toBytes("hemiprove-hub-job")),
        inputData,
        callbackExtraData: "0x",
        extraVerifierData: "0x",
        expectedJournalHash: zeroHash,
        journalFields: zeroHash,
      },
      {
        minPrice,
        maxPrice,
        rampUpPeriod: ${report.pricingRecommendation.rampUpPeriodSecs},
        curveType: 0, // Linear escalation
        fulfillmentTimeout: ${report.pricingRecommendation.fulfillmentTimeoutSecs},
        lockCollateralBps: 5000n,
        speedPremium: 0n,
        exclusivityDuration: 0,
        callbackGasLimit: 0,
        excludeFromEwma: false,
        laxCallbackMode: false,
      },
      {
        expectedCycles: ${report.cycles}n,
        cycleCommitCollateral: 0n,
        snapshotMode: 0,
        snapshotToleranceBps: 0,
        snapshotFullBonusOvershootBps: 0,
        snapshotUndershootPenaltyBps: 0,
        snapshotFullPenaltyUndershootBps: 0,
        snapshotResolverRewardBps: 0,
      },
      {
        underbidWindow: 0,
        maxBiddingDuration: 0,
        maxBidExtension: 0,
        minBidDecrement: 0n,
        bidExtensionCurveType: 0,
      },
    ],
  });

  const receipt = await publicClient.waitForTransactionReceipt({ hash: submitHash });
  console.log("Submitted HemiProve job in tx:", receipt.transactionHash);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
`;
}
